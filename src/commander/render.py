"""Readable Markdown views of a deck."""

from collections import defaultdict

from commander.models import COMMANDER_CATEGORY, Deck, DeckCard

LAND_CATEGORY = "Land"


def deck_list_markdown(deck: Deck) -> str:
    lines = [f"# {deck.name}", ""]
    commanders = " + ".join(deck.commanders) or "none set"
    bracket = str(deck.bracket) if deck.bracket is not None else "not set"
    lines += [
        f"- Commander: {commanders}",
        f"- Bracket (as set on Archidekt): {bracket}",
        f"- Cards in deck: {deck.main_count}",
        f"- Archidekt: {deck.url}",
        f"- Last edited: {deck.updated_at}",
        "",
        "<!-- Generated by `cmdr sync`; edits here are overwritten. Put notes in notes.md. -->",
    ]
    lines += _sections(deck.main_cards, heading_level=2)
    aside = tuple(card for card in deck.cards if not card.in_deck)
    if aside:
        lines += ["", "## Not in deck"]
        lines += _sections(aside, heading_level=3)
    return "\n".join(lines) + "\n"


def notes_template(deck: Deck) -> str:
    return f"# {deck.name}: notes\n\n## Game plan\n\n\n## Wants and problems\n\n\n## Change log\n\n"


def _sections(cards: tuple[DeckCard, ...], heading_level: int) -> list[str]:
    groups: defaultdict[str, list[DeckCard]] = defaultdict(list)
    for card in cards:
        groups[card.primary_category].append(card)
    lines: list[str] = []
    marker = "#" * heading_level
    for category in sorted(groups, key=_category_order):
        members = sorted(groups[category], key=lambda c: c.name.casefold())
        count = sum(card.quantity for card in members)
        lines += ["", f"{marker} {category} ({count})", ""]
        lines += [f"- {card.quantity} {card.name}" for card in members]
    return lines


def _category_order(category: str) -> tuple[int, str]:
    if category == COMMANDER_CATEGORY:
        return (0, "")
    if category == LAND_CATEGORY:
        return (2, "")
    return (1, category.casefold())
